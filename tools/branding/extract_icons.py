"""Extract selected Material "Rounded" icons (Apache-2.0) from the
material-icons-core/extended 1.7.3 sources jars into a single Kotlin file, so the
app does not depend on the (deprecated, very large) icons artifacts.

usage: extract_icons.py <unzipped-core-dir> <unzipped-ext-dir> <output.kt>
"""
import re
import sys

CORE, EXT, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
ICONS = [
    "ShowChart", "Calculate", "Star", "StarBorder", "Storefront", "Call", "Chat", "Place",
    "Directions", "Schedule", "Share", "Info", "DarkMode", "LightMode", "Refresh", "TrendingUp",
    "TrendingDown", "TrendingFlat", "Close", "Search", "SwapVert", "CloudOff", "ChevronRight",
    "Check", "Mail", "OpenInNew", "PrivacyTip", "Settings", "KeyboardArrowDown", "KeyboardArrowUp",
    "ArrowDropUp", "ArrowDropDown", "Remove", "Add", "Campaign", "Diamond", "CurrencyExchange",
    "PhotoCamera", "Language", "Lock", "Logout", "Save", "Edit", "Visibility", "VisibilityOff",
    "Backspace", "BrightnessAuto", "Public",
]


def body_of(name):
    for base in (CORE, EXT):
        path = f"{base}/commonMain/androidx/compose/material/icons/rounded/{name}.kt"
        try:
            src = open(path, encoding="utf-8").read()
        except FileNotFoundError:
            continue
        m = re.search(r'materialIcon\(name = "Rounded\.' + name + r'"(, autoMirror = true)?\) \{\n(.*?)\n        \}\n        return', src, re.S)
        if not m:
            raise SystemExit(f"cannot parse {name}")
        return m.group(1) is not None, m.group(2)
    raise SystemExit(f"icon not found: {name}")


out = [
    "/*",
    " * Icon path data from Material Icons (Rounded), Copyright The Android Open Source Project,",
    " * licensed under the Apache License, Version 2.0. Generated by tools/branding/extract_icons.py.",
    " */",
    "package com.suer.vatankuyumculuk.ui.icons",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.graphics.PathFillType",
    "import androidx.compose.ui.graphics.SolidColor",
    "import androidx.compose.ui.graphics.StrokeCap",
    "import androidx.compose.ui.graphics.StrokeJoin",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "import androidx.compose.ui.graphics.vector.PathBuilder",
    "import androidx.compose.ui.graphics.vector.path",
    "import androidx.compose.ui.unit.dp",
    "",
    "private inline fun materialIcon(",
    "    name: String,",
    "    autoMirror: Boolean = false,",
    "    block: ImageVector.Builder.() -> ImageVector.Builder,",
    "): ImageVector = ImageVector.Builder(",
    "    name = name,",
    "    defaultWidth = 24.dp,",
    "    defaultHeight = 24.dp,",
    "    viewportWidth = 24f,",
    "    viewportHeight = 24f,",
    "    autoMirror = autoMirror,",
    ").block().build()",
    "",
    "private inline fun ImageVector.Builder.materialPath(",
    "    fillAlpha: Float = 1f,",
    "    strokeAlpha: Float = 1f,",
    "    pathFillType: PathFillType = PathFillType.NonZero,",
    "    pathBuilder: PathBuilder.() -> Unit,",
    ") = path(",
    "    fill = SolidColor(Color.Black),",
    "    fillAlpha = fillAlpha,",
    "    stroke = null,",
    "    strokeAlpha = strokeAlpha,",
    "    strokeLineWidth = 1f,",
    "    strokeLineCap = StrokeCap.Butt,",
    "    strokeLineJoin = StrokeJoin.Bevel,",
    "    strokeLineMiter = 1f,",
    "    pathFillType = pathFillType,",
    "    pathBuilder = pathBuilder,",
    ")",
    "",
    "object AppIcons {",
]
for name in ICONS:
    mirror, body = body_of(name)
    body = "\n".join("    " + line[4:] if line.startswith("    ") else line for line in body.splitlines())
    mirror_arg = ", autoMirror = true" if mirror else ""
    out.append(f'    val {name}: ImageVector by lazy {{')
    out.append(f'        materialIcon(name = "{name}"{mirror_arg}) {{')
    out.append(body)
    out.append("        }")
    out.append("    }")
    out.append("")
out[-1] = "}"
open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", len(ICONS), "icons to", OUT)
