"""Builds every logo and icon file of the app from the Vatan mark.

usage: python3 tools/branding/vatan_brand.py            (run from the project root)
needs: pip install cairosvg pillow

Source of truth: store-assets/brand/mark.svg (full mark: emerald-cut bezel + faceted V),
mark-mono.svg (one-colour master) and mark-v-small.svg (frameless V for 32 px and below).
All three use viewBox 0 0 1000 1000 and only solid-fill M/L/Z paths, so they map 1:1 to
Android/Compose VectorDrawables. The full mark's tight box is x 150..850, y 100..900.
"""
import io
import os
import re

import cairosvg
from PIL import Image, ImageDraw

ROOT = os.getcwd()
BRAND = f"{ROOT}/store-assets/brand"
NAVY = (11, 16, 32)  # #0B1020
NAVY_HEX = "#0B1020"
BOX = (150, 100, 700, 800)  # x, y, w, h of the full mark inside its 1000x1000 viewBox


def read(name):
    with open(f"{BRAND}/{name}") as f:
        return f.read()


def paths(svg):
    """[(fill, pathData)] of an SVG made of <path fill=".." d=".."/> elements."""
    return re.findall(r'<path fill="(#[0-9A-Fa-f]{6})" d="([^"]+)"', svg)


def render(svg, px):
    """RGBA rendering of a 1000x1000 SVG at px x px."""
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=px, output_height=px)
    return Image.open(io.BytesIO(png)).convert("RGBA")


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(data)


def save(im, path, **kw):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path, **kw)
    print("wrote", os.path.relpath(path, ROOT))


def mark_on(size, mark_h, svg, shape="square", radius=0.0, bg=NAVY):
    """Navy tile of [size] px with the mark centred at [mark_h] (fraction of size) high.

    The mark's 1000-unit box is 800 units tall, so its render size is mark_h * size * 1000 / 800.
    """
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    tile = Image.new("RGBA", (size, size), bg + (255,))
    mask = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(mask)
    if shape == "circle":
        d.ellipse((0, 0, size - 1, size - 1), fill=255)
    elif radius:
        d.rounded_rectangle((0, 0, size - 1, size - 1), round(size * radius), fill=255)
    else:
        d.rectangle((0, 0, size - 1, size - 1), fill=255)
    canvas.paste(tile, (0, 0), mask)
    scale = 4  # supersample for crisp small sizes
    full = round(mark_h * size * scale * 1000 / 800)
    m = render(svg, full)
    off = (size * scale - full) // 2
    layer = Image.new("RGBA", (size * scale, size * scale), (0, 0, 0, 0))
    layer.paste(m, (off, off), m)
    layer = layer.resize((size, size), Image.LANCZOS)
    canvas.alpha_composite(layer)
    return canvas


def vector_xml(svg, width_dp, height_dp, viewport_w, viewport_h, tx, ty, comment):
    body = "\n".join(
        f'        <path android:fillColor="{fill}" android:pathData="{d}"/>' for fill, d in paths(svg)
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/branding/vatan_brand.py from store-assets/brand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width_dp}dp"
    android:height="{height_dp}dp"
    android:viewportWidth="{viewport_w}"
    android:viewportHeight="{viewport_h}">
    <group android:translateX="{tx}" android:translateY="{ty}">
{body}
    </group>
</vector>
"""


def main():
    mark = read("mark.svg")
    mono = read("mark-mono.svg")
    small = read("mark-v-small.svg")
    x, y, w, h = BOX

    # In-app BrandMark: viewport cropped to the mark's tight box (aspect 0.875).
    write(
        f"{ROOT}/shared/src/commonMain/composeResources/drawable/logo_mark.xml",
        vector_xml(mark, 35, 40, w, h, -x, -y, "Vatan mark, cropped to its tight box."),
    )
    # Android adaptive icon foreground: mark 46dp high on the 108dp canvas, so it fills about
    # 62% of the 72dp visible area and its farthest corner (r = 26dp) stays in the 66dp safe zone.
    vp = 1880
    write(
        f"{ROOT}/androidApp/src/main/res/drawable/ic_launcher_foreground.xml",
        vector_xml(mark, 108, 108, vp, vp, (vp - 1000) // 2, (vp - 1000) // 2,
                   "Adaptive icon foreground, also used as the monochrome layer."),
    )

    # Legacy launcher bitmaps (only used by launchers that ignore adaptive icons).
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        res = f"{ROOT}/androidApp/src/main/res/mipmap-{density}"
        save(mark_on(px, 0.62, mark, radius=0.18), f"{res}/ic_launcher.png")
        save(mark_on(px, 0.58, mark, shape="circle"), f"{res}/ic_launcher_round.png")

    # Store and iOS icons: full-bleed navy, the platforms apply their own masks.
    ios = mark_on(1024, 0.62, mark).convert("RGB")  # App Store rejects icons with alpha
    save(ios, f"{ROOT}/iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/app-icon-1024.png")
    save(ios, f"{ROOT}/store-assets/app-store/icon-1024.png")
    save(mark_on(512, 0.62, mark), f"{ROOT}/store-assets/google-play/icon-512.png")  # 32-bit for Play

    # Web.
    web = f"{ROOT}/webApp/src/webMain/resources"
    save(mark_on(180, 0.62, mark).convert("RGB"), f"{web}/apple-touch-icon.png")
    save(mark_on(192, 0.62, mark, radius=0.18), f"{web}/icons/icon-192.png")
    save(mark_on(512, 0.62, mark, radius=0.18), f"{web}/icons/icon-512.png")
    save(mark_on(512, 0.52, mark), f"{web}/icons/icon-maskable-512.png")  # inside the 80% safe circle
    save(mark_on(48, 0.74, mark, radius=0.2), f"{web}/favicon-48.png")
    fav = [mark_on(s, 0.8, small, radius=0.2) for s in (16, 32)] + [mark_on(48, 0.74, mark, radius=0.2)]
    save(fav[2], f"{web}/favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)], append_images=fav[:2])

    # Transparent mark for the feature graphic and printed material (cropped, 1600 px high).
    big = render(mark, 2000).crop((x * 2, y * 2, (x + w) * 2, (y + h) * 2))
    save(big, f"{BRAND}/mark-transparent-1600.png")
    save(render(mono, 2000).crop((x * 2, y * 2, (x + w) * 2, (y + h) * 2)), f"{BRAND}/mark-mono-1600.png")


main()
